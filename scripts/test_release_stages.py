COMMIT = "1234567890abcdef1234567890abcdef12345678"
VERSION = "9.8.7"
TAG = f"v{VERSION}"


def make_crate(path, commit=COMMIT, extra=b"", mtime=0, generated=b"", orig=True):
    """A minimal .crate: pscat-<ver>/{Cargo.toml.orig, Cargo.toml (cargo's
    normalized copy), src/lib.rs, .cargo_vcs_info.json}. `extra` changes the
    source manifest; `generated` only cargo's normalized one."""
    manifest = b'[package]\nname = "pscat"\nversion = "' + VERSION.encode() + b'"\n'
    files = {
        f"pscat-{VERSION}/Cargo.toml": b"# generated by cargo\n" + manifest + generated,
        f"pscat-{VERSION}/src/lib.rs": b"pub fn f() {}\n",
    }
    if orig:
        files[f"pscat-{VERSION}/Cargo.toml.orig"] = manifest + extra
    if commit is not None:
        files[f"pscat-{VERSION}/.cargo_vcs_info.json"] = json.dumps(
            {"git": {"sha1": commit}, "path_in_vcs": ""}).encode()
    with tarfile.open(path, "w:gz") as tar:
        for name, data in sorted(files.items()):
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mtime = mtime
            tar.addfile(info, io.BytesIO(data))


def make_dist(tmp, commit=COMMIT, payload=b"binary"):
    dist = os.path.join(tmp, "dist")
    os.makedirs(dist, exist_ok=True)
    for target, ext in (("aarch64-apple-darwin", ".tar.gz"), ("x86_64-pc-windows-msvc", ".zip")):
        with open(os.path.join(dist, f"pscat-{VERSION}-{target}{ext}"), "wb") as f:
            f.write(payload + target.encode())
    crate = os.path.join(tmp, f"pscat-{VERSION}.crate")
    make_crate(crate, commit)
    rs.write_manifest(rs.build_manifest(TAG, commit, dist, crate), dist)
    return dist, crate


class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="release-test-")
        self.repo = os.path.join(self.tmp, "repo")
        os.makedirs(self.repo)
        self.dist, self.crate = make_dist(self.tmp)
        self.m = rs.load_manifest(self.dist)
        self.fake = rs.Fake(os.path.join(self.tmp, "fake"))
        self.fake.set_tag(TAG, COMMIT)

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def ctx(self, plan=False, crate=None):
        f = self.fake
        return rs.Ctx(self.m, self.dist, crate or self.crate, self.repo, f, rs.FakeCrates(f), rs.FakeNpm(f), plan)

    def run_all(self, plan=False, crate=None):
        st, res = rs.run_stages(self.ctx(plan, crate), list(rs.STAGES))
        return st, {r["stage"]: r["result"] for r in res}, res


class Manifest(Base):
    def test_manifest_records_provenance_and_digests(self):
        self.assertEqual(self.m["tag"], TAG)
        self.assertEqual(self.m["commit"], COMMIT)
        self.assertEqual([a["name"] for a in self.m["assets"]],
                         [f"pscat-{VERSION}-aarch64-apple-darwin.tar.gz", f"pscat-{VERSION}-x86_64-pc-windows-msvc.zip"])
        with open(os.path.join(self.dist, rs.SUMS_NAME), encoding="utf-8") as f:
            self.assertEqual(f.read(), rs.sums_text(self.m["assets"]))

    def test_manifest_refuses_a_crate_from_another_commit(self):
        other = os.path.join(self.tmp, "other.crate")
        make_crate(other, commit="f" * 40)
        with self.assertRaises(SystemExit):
            rs.build_manifest(TAG, COMMIT, self.dist, other)

    def test_manifest_refuses_a_bad_tag(self):
        with self.assertRaises(SystemExit):
            rs.build_manifest("9.8.7", COMMIT, self.dist, self.crate)

    def test_crate_identity_ignores_tar_metadata(self):
        a = os.path.join(self.tmp, "a.crate")
        b = os.path.join(self.tmp, "b.crate")
        make_crate(a, mtime=0)
        make_crate(b, mtime=123456)
        self.assertNotEqual(rs.sha256_file(a), rs.sha256_file(b))
        self.assertEqual(rs.crate_identity(a), rs.crate_identity(b))


class EndToEnd(Base):
    def test_plan_then_publish_then_rerun(self):
        st, r, _ = self.run_all(plan=True)
        self.assertEqual(st, rs.EXIT_OK)
        self.assertEqual(r, {"draft": "would create", "crates": "would publish", "npm": "disabled",
                             "publish": "would publish", "plugin": "disabled"})
        self.assertEqual(self.fake.events(), [])

        st, r, _ = self.run_all()
        self.assertEqual(st, rs.EXIT_OK)
        self.assertEqual(r["draft"], "published")
        self.assertEqual(r["crates"], "published")
        self.assertEqual(r["publish"], "published")
        names = [e.split(" ", 1)[1] for e in self.fake.events() if e.startswith("github.upload")]
        self.assertEqual(names[-1], rs.MANIFEST_NAME, "the manifest goes up last")
        rel = self.fake.releases(TAG)
        self.assertEqual(len(rel), 1)
        self.assertFalse(rel[0]["draft"])

        events = self.fake.events()
        st, r, _ = self.run_all()
        self.assertEqual(st, rs.EXIT_OK)
        self.assertEqual(self.fake.events(), events, "a re-run changes nothing")
        self.assertEqual(r["draft"], "skipped")
        self.assertEqual(r["crates"], "skipped")
        self.assertEqual(r["publish"], "skipped")

    def test_report(self):
        st, _, res = self.run_all()
        rep = rs.report(self.m, res, st, False, "fake")
        md = rs.report_markdown(rep)
        self.assertIn("| crates | published |", md)
        self.assertIn(self.m["assets"][0]["sha256"], md)
        self.assertEqual(rep["status"], "ok")


class PartialFailure(Base):
    def _fail(self, op):
        with open(os.path.join(self.fake.root, "fail-once"), "w", encoding="utf-8") as f:
            f.write(op)

    def test_crates_succeeds_then_publish_fails_then_rerun(self):
        self._fail("github.publish")
        st, r, _ = self.run_all()
        self.assertEqual(st, rs.EXIT_ERROR)
        self.assertEqual(r["crates"], "published")
        self.assertEqual(r["publish"], "error")
        self.assertEqual(r["plugin"], "not run")

        st, r, _ = self.run_all()
        self.assertEqual(st, rs.EXIT_OK)
        self.assertEqual(r["crates"], "skipped")
        self.assertEqual(r["publish"], "published")
        self.assertEqual(len([e for e in self.fake.events() if e.startswith("crates.publish")]), 1)

    def test_interrupted_upload_resumes_the_draft(self):
        # The draft exists with the first archive only (the job died mid-upload).
        rid = self.fake.create_draft(TAG, "x", "x")
        first = self.m["assets"][0]["name"]
        self.fake.upload(rid, os.path.join(self.dist, first), first)
        st, r, _ = self.run_all()
        self.assertEqual(st, rs.EXIT_OK, r)
        rel = self.fake.releases(TAG)[0]
        self.assertEqual(sorted(a["name"] for a in rel["assets"]), sorted(rs.release_files(self.m)))

    def test_rebuilt_artifacts_adopt_a_complete_draft(self):
        # Run 1 made the whole draft, then the job failed before crates.io.
        self._fail("crates.publish")
        st, r, _ = self.run_all()
        self.assertEqual((st, r["draft"], r["crates"]), (rs.EXIT_ERROR, "published", "error"))
        # Run 2 rebuilt the binaries from the same commit: different bytes.
        shutil.rmtree(self.dist)
        self.dist, _ = make_dist(self.tmp, payload=b"rebuilt")
        self.m = rs.load_manifest(self.dist)
        st, r, _ = self.run_all()
        self.assertEqual(st, rs.EXIT_OK, r)
        self.assertEqual(r["draft"], "skipped")

    def test_crate_from_another_cargo_version_matches(self):
        # cargo's normalized Cargo.toml differs, the source is the same.
        self.fake.publish_crate(self.crate)
        other = os.path.join(self.tmp, "newer-cargo", f"pscat-{VERSION}.crate")
        os.makedirs(os.path.dirname(other))
        make_crate(other, generated=b"autolib = false\n")
        st, r, res = self.run_all(crate=other)
        self.assertEqual(st, rs.EXIT_OK, res)
        self.assertEqual(r["crates"], "skipped")

    def test_crates_identity_from_a_repackaged_crate(self):
        # Same commit and contents, packaged again (different tar mtimes).
        self.fake.publish_crate(self.crate)
        again = os.path.join(self.tmp, "again", f"pscat-{VERSION}.crate")
        os.makedirs(os.path.dirname(again))
        make_crate(again, mtime=99)
        st, r, res = self.run_all(crate=again)
        self.assertEqual(st, rs.EXIT_OK, res)
        self.assertEqual(r["crates"], "skipped")


class Mismatch(Base):
    def test_different_crate_at_the_version_halts(self):
        other = os.path.join(self.tmp, "x", f"pscat-{VERSION}.crate")
        os.makedirs(os.path.dirname(other))
        make_crate(other, extra=b"# different\n")
        self.fake.publish_crate(other)
        st, r, _ = self.run_all()
        self.assertEqual(st, rs.EXIT_HALT)
        self.assertEqual(r["crates"], "halted")
        self.assertEqual(r["publish"], "not run")
        self.assertTrue(self.fake.releases(TAG)[0]["draft"], "the GitHub release stays a draft")

    def test_crate_from_another_commit_halts(self):
        other = os.path.join(self.tmp, "x", f"pscat-{VERSION}.crate")
        os.makedirs(os.path.dirname(other))
        make_crate(other, commit="f" * 40)
        self.fake.publish_crate(other)
        st, r, res = self.run_all()
        self.assertEqual((st, r["crates"]), (rs.EXIT_HALT, "halted"))
        self.assertIn("published from", res[1]["detail"])

    def test_crate_without_source_manifest_halts(self):
        other = os.path.join(self.tmp, "x", f"pscat-{VERSION}.crate")
        os.makedirs(os.path.dirname(other))
        make_crate(other, orig=False)
        self.fake.publish_crate(other)
        st, r, _ = self.run_all()
        self.assertEqual((st, r["crates"]), (rs.EXIT_HALT, "halted"))

    def test_crate_without_vcs_info_halts(self):
        other = os.path.join(self.tmp, "x", f"pscat-{VERSION}.crate")
        os.makedirs(os.path.dirname(other))
        make_crate(other, commit=None)
        self.fake.publish_crate(other)
        st, r, _ = self.run_all()
        self.assertEqual((st, r["crates"]), (rs.EXIT_HALT, "halted"))

    def test_published_release_with_a_different_archive_halts(self):
        rid = self.fake.create_draft(TAG, "x", "x")
        bogus = os.path.join(self.tmp, "bogus")
        with open(bogus, "wb") as f:
            f.write(b"not ours")
        self.fake.upload(rid, bogus, self.m["assets"][0]["name"])
        self.fake.publish(rid)
        st, r, _ = self.run_all()
        self.assertEqual((st, r["draft"], r["crates"]), (rs.EXIT_HALT, "halted", "not run"))

    def test_published_release_missing_assets_halts(self):
        rid = self.fake.create_draft(TAG, "x", "x")
        first = self.m["assets"][0]["name"]
        self.fake.upload(rid, os.path.join(self.dist, first), first)
        self.fake.publish(rid)
        st, r, _ = self.run_all()
        self.assertEqual((st, r["draft"]), (rs.EXIT_HALT, "halted"))

    def test_unexpected_asset_halts(self):
        rid = self.fake.create_draft(TAG, "x", "x")
        self.fake.upload(rid, self.crate, "surprise.bin")
        st, r, _ = self.run_all()
        self.assertEqual((st, r["draft"]), (rs.EXIT_HALT, "halted"))

    def test_two_drafts_for_the_tag_halt(self):
        self.fake.create_draft(TAG, "x", "x")
        self.fake.create_draft(TAG, "y", "y")
        st, r, _ = self.run_all()
        self.assertEqual((st, r["draft"]), (rs.EXIT_HALT, "halted"))

    def test_draft_from_another_commit_halts(self):
        rid = self.fake.create_draft(TAG, "x", "x")
        p = os.path.join(self.tmp, rs.MANIFEST_NAME)
        with open(p, "w", encoding="utf-8") as f:
            json.dump(dict(self.m, commit="0" * 40), f)
        self.fake.upload(rid, p, rs.MANIFEST_NAME)
        st, r, _ = self.run_all()
        self.assertEqual((st, r["draft"]), (rs.EXIT_HALT, "halted"))

    def test_missing_or_moved_tag_halts_before_creating_anything(self):
        self.fake.set_tag(TAG, "e" * 40)
        st, r, _ = self.run_all()
        self.assertEqual((st, r["draft"]), (rs.EXIT_HALT, "halted"))
        self.assertEqual(self.fake.events(), [])
        fake2 = rs.Fake(os.path.join(self.tmp, "fake2"))
        st, res = rs.run_stages(rs.Ctx(self.m, self.dist, self.crate, self.repo, fake2, rs.FakeCrates(fake2),
                                       rs.FakeNpm(fake2), False), ["draft"])
        self.assertEqual(st, rs.EXIT_HALT)
        self.assertIn("does not exist", res[0]["detail"])


class Channels(Base):
    def _npm(self, version=VERSION):
        os.makedirs(os.path.join(self.repo, "npm"), exist_ok=True)
        with open(os.path.join(self.repo, "npm", "package.json"), "w", encoding="utf-8") as f:
            json.dump({"name": "pscat-wasm", "version": version}, f)

    def test_npm_runs_only_when_npm_package_exists(self):
        st, r, _ = self.run_all()
        self.assertEqual(r["npm"], "disabled")
        self._npm()
        fake = rs.Fake(os.path.join(self.tmp, "fake-npm"))
        fake.set_tag(TAG, COMMIT)
        self.fake = fake
        st, r, _ = self.run_all()
        self.assertEqual((st, r["npm"]), (rs.EXIT_OK, "published"))
        st, r, _ = self.run_all()
        self.assertEqual((st, r["npm"]), (rs.EXIT_OK, "skipped"))

    def test_npm_mismatch_halts(self):
        self._npm()
        self.fake.npm_publish("pscat-wasm", VERSION, "sha512-somethingelse")
        st, r, _ = self.run_all()
        self.assertEqual((st, r["npm"], r["publish"]), (rs.EXIT_HALT, "halted", "not run"))

    def test_npm_version_must_match(self):
        self._npm("0.0.1")
        st, r, _ = self.run_all()
        self.assertEqual((st, r["npm"]), (rs.EXIT_HALT, "halted"))

    def test_plugin_manifest_versions(self):
        d = os.path.join(self.repo, "plugins", "pscat", ".claude-plugin")
        os.makedirs(d)
        with open(os.path.join(d, "plugin.json"), "w", encoding="utf-8") as f:
            json.dump({"name": "pscat", "version": "0.0.1"}, f)
        st, r, _ = self.run_all()
        self.assertEqual((st, r["plugin"]), (rs.EXIT_HALT, "halted"))
        changed = rs.bump_manifests_json_only(self.repo, VERSION)
        self.assertEqual(changed, [os.path.join("plugins", "pscat", ".claude-plugin", "plugin.json")])
        fake = rs.Fake(os.path.join(self.tmp, "fake-plugin"))
        fake.set_tag(TAG, COMMIT)
        self.fake = fake
        st, r, _ = self.run_all()
        self.assertEqual((st, r["plugin"]), (rs.EXIT_OK, "skipped"))


class RepoFacts(unittest.TestCase):
    def test_pin_reader(self):
        with tempfile.TemporaryDirectory() as d:
            os.makedirs(os.path.join(d, "src", "fontpacks"))
            p = os.path.join(d, "src", "fontpacks", "pinned.rs")
            with open(p, "w", encoding="utf-8") as f:
                f.write("pub const PINNED_INDEX: Option<Pinned> = None;\n")
            self.assertIsNone(rs.pinned_index(d))
            with open(p, "w", encoding="utf-8") as f:
                f.write('pub const PINNED_INDEX: Option<Pinned> = Some(Pinned {\n    tag: "fonts-2026.10",\n'
                        '    sha256: "' + "a" * 64 + '",\n});\n')
            self.assertEqual(rs.pinned_index(d), ("fonts-2026.10", "a" * 64))

    def test_the_checked_in_pin_parses(self):
        rs.pinned_index()  # None or a pin; never a parse failure

    def test_cargo_version_bump(self):
        with tempfile.TemporaryDirectory() as d:
            with open(os.path.join(d, "Cargo.toml"), "w", encoding="utf-8") as f:
                f.write('[package]\nname = "pscat"\nversion = "0.5.1"\n\n[dependencies]\nx = { version = "1" }\n')
            changed = rs.bump_manifests(d, "0.6.0")
            self.assertEqual(changed, ["Cargo.toml"])
            self.assertEqual(rs.cargo_version(d), "0.6.0")
            with open(os.path.join(d, "Cargo.toml"), encoding="utf-8") as f:
                self.assertIn('x = { version = "1" }', f.read())
            with self.assertRaises(SystemExit):
                rs.bump_manifests(d, "0.6")

    def test_rehearse_passes_on_synthetic_artifacts(self):
        with tempfile.TemporaryDirectory() as d:
            dist, crate = make_dist(d)
            outcomes = rs.rehearse(dist, crate, d, log=lambda *_: None)
            self.assertTrue(outcomes)
            self.assertEqual([n for n, ok, _ in outcomes if not ok], [])


@unittest.skipUnless(shutil.which("git-cliff"), "git-cliff not installed")
class ReleaseScript(unittest.TestCase):
    """scripts/release.sh --no-push in a scratch clone of this repo."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="release-sh-")
        self.clone = os.path.join(self.tmp, "clone")
        subprocess.run(["git", "clone", "--quiet", "--no-local", rs.ROOT, self.clone], check=True)
        # Work on whatever is checked out here (the PR's tree), as `main`.
        head = subprocess.run(["git", "-C", rs.ROOT, "rev-parse", "HEAD"], capture_output=True, text=True,
                              check=True).stdout.strip()
        subprocess.run(["git", "-C", self.clone, "checkout", "--quiet", "-B", "main", head], check=True)
        for name in ("scripts/release.sh", "scripts/release_stages.py", "cliff.toml"):
            shutil.copyfile(os.path.join(rs.ROOT, name), os.path.join(self.clone, name))
        subprocess.run(["git", "-C", self.clone, "-c", "user.name=t", "-c", "user.email=t@example.com",
                        "commit", "--quiet", "--allow-empty", "-am", "test: the tree under test"], check=True)

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def release(self, *args):
        env = dict(os.environ, GIT_AUTHOR_NAME="t", GIT_AUTHOR_EMAIL="t@example.com",
                   GIT_COMMITTER_NAME="t", GIT_COMMITTER_EMAIL="t@example.com", RELEASE_SKIP_FETCH="1")
        return subprocess.run(["bash", "scripts/release.sh", *args], cwd=self.clone, env=env,
                              capture_output=True, text=True)

    def test_refuses_while_unpinned(self):
        if rs.pinned_index(self.clone) is not None:
            self.skipTest("the font index is pinned")
        p = self.release("99.0.0", "--no-push")
        self.assertNotEqual(p.returncode, 0)
        self.assertIn("PINNED_INDEX = None", p.stderr)

    def test_bumps_versions_and_writes_the_changelog(self):
        p = self.release("99.0.0", "--no-push", "--allow-unpinned")
        self.assertEqual(p.returncode, 0, p.stdout + p.stderr)
        self.assertEqual(rs.cargo_version(self.clone), "99.0.0")
        with open(os.path.join(self.clone, "Cargo.lock"), encoding="utf-8") as f:
            self.assertIn('name = "pscat"\nversion = "99.0.0"', f.read())
        with open(os.path.join(self.clone, "CHANGELOG.md"), encoding="utf-8") as f:
            text = f.read()
        self.assertIn("## [99.0.0]", text)
        branch = subprocess.run(["git", "-C", self.clone, "branch", "--show-current"], capture_output=True,
                                text=True).stdout.strip()
        self.assertEqual(branch, "release/v99.0.0")
        msg = subprocess.run(["git", "-C", self.clone, "log", "-1", "--format=%s"], capture_output=True,
                             text=True).stdout.strip()
        self.assertEqual(msg, "release: 99.0.0")

    def test_refuses_a_version_that_is_not_newer(self):
        p = self.release("0.0.1", "--no-push", "--allow-unpinned")
        self.assertNotEqual(p.returncode, 0)
        self.assertIn("not newer", p.stderr)

    def test_refuses_a_dirty_tree(self):
        with open(os.path.join(self.clone, "README.md"), "a", encoding="utf-8") as f:
            f.write("dirty\n")
        p = self.release("99.0.0", "--no-push", "--allow-unpinned")
        self.assertNotEqual(p.returncode, 0)
        self.assertIn("uncommitted", p.stderr)


