#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ascii_range_is_dense_and_shared() {
        let std = standard_encoding();
        let iso = iso_latin1_encoding();
        for c in 0x20..0x7f {
            assert_ne!(std[c], ".notdef", "standard {c:#x}");
            assert_eq!(std[c], iso[c], "ascii range shared at {c:#x}");
        }
        assert_eq!(std[b'A' as usize], "A");
        assert_eq!(std[0x27], "quoteright");
        assert_eq!(std[0x60], "quoteleft");
    }

    #[test]
    fn high_ranges_differ_per_appendix_e() {
        let std = standard_encoding();
        let iso = iso_latin1_encoding();
        assert_eq!(std[0o251], "quotesingle");
        assert_eq!(std[0o260], ".notdef");
        assert_eq!(std[0o320], "emdash");
        assert_eq!(iso[0o351], "eacute");
        assert_eq!(iso[0o240], "space");
        assert_eq!(iso[0o255], "hyphen");
    }

    #[test]
    fn every_encoded_name_has_a_unicode_fallback() {
        for name in standard_encoding()
            .iter()
            .chain(iso_latin1_encoding().iter())
        {
            if *name != ".notdef" {
                assert!(name_to_char(name).is_some(), "no unicode for {name}");
            }
        }
    }
}
