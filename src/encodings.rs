fn build(high: &[(u8, &'static str)]) -> [&'static str; 256] {
    let mut names = [".notdef"; 256];
    for (i, n) in ASCII_NAMES.into_iter().enumerate() {
        names[0x20 + i] = n;
    }
    for &(code, name) in high {
        names[code as usize] = name;
    }
    names
}

pub fn standard_encoding() -> [&'static str; 256] {
    build(STANDARD_HIGH)
}

pub fn iso_latin1_encoding() -> [&'static str; 256] {
    build(ISO_LATIN1_HIGH)
}

